/** @fileoverview Defines collections, tags, their actual memberships, and closed saved-query definitions. */

import * as v from 'valibot'
import type { DefinitionRead } from '../definition'
import { invalidInput } from '../errors'
import type { CallOptions, ListOptions, ListResult } from '../execution'
import { preparedAttachmentSchema, type PreparedAttachment } from '../resources'
import { objectSchema } from '../schema'
import {
  exactPartialEntries,
  hasRelatedExpected,
  hasUniqueKeys,
  nonemptyStringSchema,
  parseContract,
} from '../validation'
import { entryRefSchema, type EntryRef } from './identity'
import type { MoveInput, OrderChange } from './ordering'
import { parseEntryQuery, type EntryRule, type EntrySort } from './queries'

/** A bounded name snapshot for a real reference, never an alternate identity or lookup instruction. */
export interface QueryReferenceLabel {
  readonly target: EntryRef | { readonly type: 'tag' | 'collection' | 'note'; readonly id: string }
  readonly name: string
}
/** Dynamic membership evaluates across the real library and always has an explicit field/part sort. */
export interface DynamicCollectionRules {
  readonly search: string
  readonly rules: readonly EntryRule[]
  readonly sort: Exclude<EntrySort, { type: 'scope' }>
  readonly referenceLabels: readonly QueryReferenceLabel[]
}
interface CollectionFields {
  readonly id: string
  readonly name: string
  readonly description: string | null
  readonly primaryImageId: string | null
  readonly isNsfw: boolean
  readonly sortOrder: number
  readonly createdAt: number
  readonly updatedAt: number
}
/** The two actual member modes cannot be mixed, including when a stored dynamic definition is invalid. */
export type Collection = CollectionFields &
  (
    | { readonly membershipMode: 'manual'; readonly dynamicRules: null }
    | {
        readonly membershipMode: 'dynamic'
        readonly dynamicRules: DefinitionRead<DynamicCollectionRules>
      }
  )
export type CollectionSummary = Omit<CollectionFields, 'description'> & {
  readonly membershipMode: 'manual' | 'dynamic'
}
export interface CollectionMember {
  readonly entry: EntryRef
  readonly note: string | null
}
export type CollectionMembersChange =
  | { readonly type: 'replace'; readonly items: readonly CollectionMember[] }
  | {
      readonly type: 'modify'
      readonly add?: readonly CollectionMember[]
      readonly remove?: readonly EntryRef[]
    }
/** Initial manual members are explicit; dynamic creation carries a complete legal definition. */
export type CollectionCreate = {
  readonly name: string
  readonly description?: string | null
  readonly primaryImageId?: string | null
  readonly isNsfw?: boolean
  readonly prepared?: readonly PreparedAttachment[]
} & (
  | {
      readonly membershipMode?: 'manual'
      readonly members?: readonly { readonly entry: EntryRef; readonly note?: string | null }[]
    }
  | { readonly membershipMode: 'dynamic'; readonly dynamicRules: DynamicCollectionRules }
)
export interface CollectionUpdate {
  readonly changes: {
    readonly name?: string
    readonly description?: string | null
    readonly primaryImageId?: string | null
    readonly isNsfw?: boolean
    readonly dynamicRules?: DynamicCollectionRules
  }
  readonly expected?: {
    readonly name?: string
    readonly description?: string | null
    readonly primaryImageId?: string | null
    readonly isNsfw?: boolean
    readonly dynamicRules?: DynamicCollectionRules
  }
  readonly prepared?: readonly PreparedAttachment[]
}
export interface CollectionQuery {
  readonly search: string
  readonly membershipMode?: 'manual' | 'dynamic'
  readonly sort:
    | { readonly type: 'scope' }
    | {
        readonly type: 'field'
        readonly field: 'name' | 'createdAt' | 'updatedAt'
        readonly direction: 'asc' | 'desc'
      }
}

/** A reusable flat tag. Matching keys are generated by the owner, never accepted as an editable field. */
export interface Tag {
  readonly id: string
  readonly name: string
  readonly description: string | null
  readonly isNsfw: boolean
  readonly createdAt: number
  readonly updatedAt: number
}
export type TagSummary = Omit<Tag, 'description'>
export interface TagCreate {
  readonly name: string
  readonly description?: string | null
  readonly isNsfw?: boolean
  readonly prepared?: readonly PreparedAttachment[]
}
export interface TagUpdate {
  readonly changes: Omit<Partial<TagCreate>, 'prepared'>
  readonly expected?: Omit<Partial<TagCreate>, 'prepared'>
  readonly prepared?: readonly PreparedAttachment[]
}
export interface TagQuery {
  readonly search: string
  readonly unused?: boolean
  readonly sort:
    | { readonly type: 'scope' }
    | {
        readonly type: 'field'
        readonly field: 'name' | 'createdAt' | 'updatedAt'
        readonly direction: 'asc' | 'desc'
      }
}

const organizerSortSchema = v.union([
  objectSchema({ type: v.literal('scope') }),
  objectSchema({
    type: v.literal('field'),
    field: v.picklist(['name', 'createdAt', 'updatedAt']),
    direction: v.picklist(['asc', 'desc']),
  }),
])
/** Validate collection queries independently of saved showcase or dynamic-member definitions. */
export function parseCollectionQuery(input: unknown): CollectionQuery {
  return parseContract(
    objectSchema({
      search: v.string(),
      membershipMode: v.exactOptional(v.picklist(['manual', 'dynamic'])),
      sort: organizerSortSchema,
    }),
    input,
    'collection query',
  )
}
/** Validate tag queries; tags have no global manual ordering or image projection. */
export function parseTagQuery(input: unknown): TagQuery {
  return parseContract(
    objectSchema({
      search: v.string(),
      unused: v.exactOptional(v.boolean()),
      sort: organizerSortSchema,
    }),
    input,
    'tag query',
  )
}
export interface TagEntry {
  readonly entry: EntryRef
  readonly note: string | null
  readonly isSpoiler: boolean
}
export type TagEntriesChange =
  | { readonly type: 'replace'; readonly items: readonly TagEntry[] }
  | {
      readonly type: 'modify'
      readonly add?: readonly TagEntry[]
      readonly remove?: readonly EntryRef[]
    }
/** Ordered source identities merge into a distinct retained identity under the fixed organizer rules. */
export interface OrganizerMergeInput {
  readonly sourceIds: readonly [string, ...string[]]
  readonly targetId: string
}
export interface OrganizerMergeResult {
  readonly targetId: string
  readonly removedIds: readonly string[]
}

/** Collections manage their own metadata and actual manual members; dynamic views never write member mirrors. */
export interface CollectionsApi {
  /** Read bounded summaries and the same query's total in the selected stable order. */
  list(
    query: CollectionQuery,
    options: ListOptions,
    call?: CallOptions,
  ): Promise<ListResult<CollectionSummary>>
  /** Read the saved definition or null, retaining an explicit invalid dynamic state. */
  get(id: string, call?: CallOptions): Promise<Collection | null>
  /** Create the collection and supplied manual members together. */
  create(input: CollectionCreate, call?: CallOptions): Promise<string>
  /** Save only changed fields; ordinary update cannot change member mode. */
  update(id: string, input: CollectionUpdate, call?: CallOptions): Promise<void>
  /** Delete the collection and its links without deleting entries or their files. */
  delete(id: string, call?: CallOptions): Promise<void>
  /** Evaluate the full real library and atomically convert the matching original dynamic definition to manual members. */
  convertToManual(
    id: string,
    input: { readonly expected: { readonly dynamicRules: DynamicCollectionRules } },
    call?: CallOptions,
  ): Promise<void>
  /** Merge manual collections only; dynamic participants require a separate explicit conversion. */
  merge(input: OrganizerMergeInput, call?: CallOptions): Promise<OrganizerMergeResult>
  /** Reorder the global collection list, including hidden members in the expected baseline. */
  reorder(input: OrderChange, call?: CallOptions): Promise<void>
  /** Move current collection identities before a current anchor. */
  move(input: MoveInput, call?: CallOptions): Promise<void>
  readonly members: {
    /** Apply one complete manual-side membership intent; expected is valid only for replace. */
    applyChanges(
      collectionId: string,
      input: {
        readonly change: CollectionMembersChange
        readonly expected?: { readonly members: readonly CollectionMember[] }
      },
      call?: CallOptions,
    ): Promise<void>
    /** Edit only this actual member's note, without changing other members or the entry itself. */
    update(
      collectionId: string,
      entry: EntryRef,
      input: {
        readonly changes: { readonly note: string | null }
        readonly expected?: { readonly note: string | null }
      },
      call?: CallOptions,
    ): Promise<void>
    /** Reorder this manual collection's complete side without changing the global collection order. */
    reorder(collectionId: string, input: OrderChange, call?: CallOptions): Promise<void>
    /** Express a current-position intent within this manual collection. */
    move(collectionId: string, input: MoveInput, call?: CallOptions): Promise<void>
  }
}

/** Tags preserve independent identity and metadata even after their last entry link is removed. */
export interface TagsApi {
  /** Read summaries and total; global tags have no artificial manual-order field. */
  list(query: TagQuery, options: ListOptions, call?: CallOptions): Promise<ListResult<TagSummary>>
  /** Read the saved tag or null. */
  get(id: string, call?: CallOptions): Promise<Tag | null>
  /** Create an explicit new tag; an existing name key is a conflict, not an implicit merge. */
  create(input: TagCreate, call?: CallOptions): Promise<string>
  /** Compare changed metadata only and keep membership attributes independent. */
  update(id: string, input: TagUpdate, call?: CallOptions): Promise<void>
  /** Remove the tag and applications, retaining all entries and user files. */
  delete(id: string, call?: CallOptions): Promise<void>
  /** Merge explicitly selected identities under the fixed metadata, note, spoiler, and ordering rules. */
  merge(input: OrganizerMergeInput, call?: CallOptions): Promise<OrganizerMergeResult>
  readonly entries: {
    /** Apply one complete tag-side membership intent; replacing a visible fragment is not permitted. */
    applyChanges(
      tagId: string,
      input: {
        readonly change: TagEntriesChange
        readonly expected?: { readonly entries: readonly TagEntry[] }
      },
      call?: CallOptions,
    ): Promise<void>
    /** Edit the real application attributes without changing tag metadata or opposite-side order. */
    update(
      tagId: string,
      entry: EntryRef,
      input: {
        readonly changes: { readonly note?: string | null; readonly isSpoiler?: boolean }
        readonly expected?: { readonly note?: string | null; readonly isSpoiler?: boolean }
      },
      call?: CallOptions,
    ): Promise<void>
    /** Reorder this tag's entry side against its complete original sequence. */
    reorder(tagId: string, input: OrderChange, call?: CallOptions): Promise<void>
    /** Move actual current applications before a real anchor. */
    move(tagId: string, input: MoveInput, call?: CallOptions): Promise<void>
  }
}

export const queryReferenceLabelsSchema = v.pipe(
  v.array(
    objectSchema({
      target: v.union([
        entryRefSchema,
        objectSchema({ type: v.picklist(['tag', 'collection', 'note']), id: nonemptyStringSchema }),
      ]),
      name: nonemptyStringSchema,
    }),
  ),
  v.check((values) => hasUniqueKeys(values, (value) => JSON.stringify(value.target))),
  v.readonly(),
)
const description = v.pipe(
  v.nullable(v.string()),
  v.transform((value) => (value === null || value.trim() === '' ? null : value)),
)
const name = v.pipe(v.string(), v.trim(), v.nonEmpty())
const tagFields = { name, description, isNsfw: v.boolean() }
const prepared = v.exactOptional(v.pipe(v.array(preparedAttachmentSchema), v.readonly()))

/** Parse the saved query grammar; existence, visibility, and canonical reference labels remain owner checks. */
export function parseDynamicCollectionRules(input: unknown): DynamicCollectionRules {
  const value = parseContract(
    objectSchema({
      search: v.string(),
      rules: v.unknown(),
      sort: v.unknown(),
      referenceLabels: queryReferenceLabelsSchema,
    }),
    input,
    'dynamic collection rules',
  )
  const query = parseEntryQuery({
    scope: { type: 'library' },
    search: value.search,
    rules: value.rules,
    sort: value.sort,
  })
  if (query.sort.type === 'scope') {
    return invalidInput('Dynamic collections require an explicit field or part sort.')
  }
  return {
    search: query.search,
    rules: query.rules,
    sort: query.sort,
    referenceLabels: value.referenceLabels,
  }
}
/** Strictly validate tag metadata without accepting covers, namespaces, global order, or generated keys. */
export function parseTagCreate(input: unknown): TagCreate {
  return parseContract(
    objectSchema({
      name,
      description: v.exactOptional(description),
      isNsfw: v.exactOptional(v.boolean()),
      prepared,
    }),
    input,
    'tag creation',
  )
}
/** Validate independent tag field changes and only their related original values. */
export function parseTagUpdate(input: unknown): TagUpdate {
  const fields = objectSchema(exactPartialEntries(tagFields))
  return parseContract(
    v.pipe(
      objectSchema({ changes: fields, expected: v.exactOptional(fields), prepared }),
      v.check((value) => hasRelatedExpected(value.changes, value.expected)),
    ),
    input,
    'tag update',
  )
}
/** Produce the exact tag-name matching key while preserving the display name elsewhere. */
export function normalizeTagNameKey(input: string): string {
  return parseContract(name, input, 'tag name')
    .normalize('NFKC')
    .trim()
    .replace(/\s+/gu, ' ')
    .toLowerCase()
}
/** Validate distinct ordered sources and a separate retained organizer identity. */
export function parseOrganizerMerge(input: unknown): OrganizerMergeInput {
  return parseContract(
    v.pipe(
      objectSchema({
        sourceIds: v.pipe(
          v.tupleWithRest([nonemptyStringSchema], nonemptyStringSchema),
          v.readonly(),
        ),
        targetId: nonemptyStringSchema,
      }),
      v.check(
        (value) =>
          hasUniqueKeys(value.sourceIds, (id) => id) && !value.sourceIds.includes(value.targetId),
      ),
    ),
    input,
    'organizer merge',
  )
}
